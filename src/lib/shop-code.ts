/**
 * 店家代碼（`tenants.shop_code`）的形狀 —— 四個地方共用同一個來源
 * -----------------------------------------------------------------------------
 * 這個檔存在的理由很具體：2026-09-08 的最終風險評估指出同一個規則散在好幾層，而且
 * 彼此不一致。第一次收斂時我只收了註冊 API，於是**設定 API 這個第二個寫入者被漏掉**
 * ——而我在檔頭寫的是「三個地方共用同一個來源」。那句話當時不成立（PB-027：註解說了
 * 程式沒做到的事），是下一輪風險評估抓出來的。現在四個地方全部從這裡取：
 *
 *   | 位置 | 角色 | 原本的規則 |
 *   |---|---|---|
 *   | DB（`0003_tenants_and_accounts.sql`） | 最終防線 | `check (shop_code ~ '^[a-z0-9-]+$')`，**無長度上限** |
 *   | `POST /api/auth/tenant/register` | 寫入者① | `/^[a-z0-9-]+$/`，**無長度上限** |
 *   | `PUT /api/settings`（`basicSettingsSchema`） | 寫入者② | `/^[a-z0-9-]+$/`，**無長度上限** |
 *   | `/tenant/register` 前端 | 送出前驗證 | 自己的第三份 `/^[a-z0-9-]+$/` |
 *   | `/s/{shopCode}` 公開頁 | 讀取者 | `^[a-z0-9-]{1,64}$` |
 *
 * 後果不是理論上的：一家店把代碼設成 65 字元以上，後台會照常把 `/s/{shopCode}`
 * 顯示成「你的公開預約網址」（`settings/page.tsx` 就在同一頁顯示它），而那個網址
 * 永遠 404 —— **正是 issue #299 要修掉的那類「介面說有、實際沒有」**。在同一個 PR
 * 裡新造一個同形狀的缺陷，說不過去。
 *
 * ⚠️ 所以判準是「**每一個會寫入 `tenants.shop_code` 的入口**」，不是「我想到的那
 * 幾個」。日後再增加寫入者時，同一句話仍然要成立。
 *
 * ⚠️ 長度上限 64 是**這一層新加的**，DB 上沒有。加它的動機是公開頁：那是全站第一個
 * 匿名就打得到資料庫的路徑，而專案目前沒有任何 rate limit —— 一個 2000 字元的亂碼
 * 網址不該換到一次 service-role 查詢。查證過正式庫與共用 TEST，現有代碼最長 11 字元，
 * 沒有任何一筆會被這個上限擋掉。
 */
export const SHOP_CODE_MAX_LENGTH = 64;

/** 與 DB 的 check constraint 同形狀，另加上長度上限（理由見檔頭）。 */
export const SHOP_CODE_PATTERN = new RegExp(`^[a-z0-9-]{1,${SHOP_CODE_MAX_LENGTH}}$`);

export const SHOP_CODE_MESSAGE = `僅限小寫英文、數字、連字號，且不超過 ${SHOP_CODE_MAX_LENGTH} 字`;
